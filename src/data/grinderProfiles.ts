/**
 * Approximate conversion between Mischief M40 clicks and LEnodi clicks
 * Based on burr pitch: M40 is ~30µm/click, LEnodi is ~22µm/click
 */
export function convertClicks(fromGrinder: 'mischief-m40' | 'lenodi', clicks: number): number {
  if (fromGrinder === 'mischief-m40') {
    // M40 to LEnodi
    const targetMicrons = clicks * 30;
    return Math.round(targetMicrons / 22);
  } else {
    // LEnodi to M40
    const targetMicrons = clicks * 22;
    return Math.round(targetMicrons / 30);
  }
}
