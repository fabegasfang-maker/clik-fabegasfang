/**
 * Approximate conversion between Mischief M40 clicks (15.2µm/click) and LEnodi clicks (22µm/click)
 */
export function convertClicks(fromGrinder: 'mischief-m40' | 'lenodi', clicks: number): number {
  if (fromGrinder === 'mischief-m40') {
    // M40 to LEnodi
    const targetMicrons = clicks * 15.2;
    return Math.round(targetMicrons / 22);
  } else {
    // LEnodi to M40
    const targetMicrons = clicks * 22;
    return Math.round(targetMicrons / 15.2);
  }
}

